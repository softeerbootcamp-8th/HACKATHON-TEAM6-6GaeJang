package com.delipot.pot;

/**
 * 팟의 생애주기. 기획서의 총대 흐름(모집 → 정산 → 주문 → 수령)을 그대로 따른다.
 * enum 이름이 그대로 응답 JSON에 나가므로 프론트와의 계약이다.
 */
public enum PotStatus {

	/** 모집 중. 멤버가 참여하고 메뉴를 전달할 수 있다. */
	RECRUITING,

	/** 마감(정원 충족 또는 마감시간 도달). 정산·송금 확인 단계. */
	CLOSED,

	/** 총대가 외부 배달앱에서 실제 주문을 완료했다. */
	ORDERED,

	/** 배달 수령 및 분배까지 끝났다. */
	DONE
}
