package com.delipot.pot;

/**
 * 팟의 생애주기. 상태가 답하는 질문은 하나다 — "이 팟이 아직 살아 있는가".
 *
 * <p>enum 이름이 그대로 응답 JSON에 나가므로 프론트와의 계약이다. 이름을 바꾸면 프론트가 깨진다.
 *
 * <p>"지금 참여할 수 있는가"는 여기 없다. {@code deadline > now}로 언제든 계산되는 값이라
 * 컬럼으로 두면 시각이 흐를 때마다 갱신해야 한다. 그래서 마감이 지난 팟도 {@link #ACTIVE}다.
 */
public enum PotStatus {

	/** 살아 있는 팟. 마감시간이 지났는지와 무관하게 참여자·총대의 목록에 계속 뜬다. */
	ACTIVE,

	/**
	 * 나눔 완료. 참여자를 포함한 모두의 목록에서 사라진다. 채팅방은 그대로 남는다.
	 * 총대의 나눔 완료 버튼, 또는 마감시간 + 5시간 경과로 자동 전이된다.
	 */
	DONE
}
