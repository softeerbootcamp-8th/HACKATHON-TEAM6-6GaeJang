package com.delipot.pot;

/**
 * 팟의 생애주기. 상태가 답하는 질문은 하나다 — "이 팟이 아직 살아 있는가".
 *
 * <p>enum 이름이 그대로 응답 JSON에 나가므로 프론트와의 계약이다.
 *
 * <p>"모집 중인가"는 여기 없다. 팟에는 성질이 다른 두 축이 있는데, 그중 하나만 저장해야 한다.
 * <ul>
 *   <li><b>살아 있는가</b> — 이벤트로 바뀐다(총대가 나눔 완료를 누른다, 유예 시간이 지난다).
 *       계산할 수 없으니 컬럼으로 저장한다. 그게 이 enum이다.</li>
 *   <li><b>지금 참여할 수 있는가</b> — {@code deadline > now} 비교로 언제든 계산된다.
 *       컬럼으로 두면 시각이 흐를 때마다 누군가 갱신해야 하고, 갱신 전까지 두 값이 어긋난다.</li>
 * </ul>
 *
 * <p>그래서 마감시간이 지난 팟도 {@link #ACTIVE}다 — 살아는 있고 새로 못 들어올 뿐이다.
 * 참여 가능 여부는 응답의 {@code isDeadlinePassed} 같은 계산 필드로 내려준다.
 */
public enum PotStatus {

	/**
	 * 살아 있는 팟. 참여자·총대의 목록에 계속 뜬다.
	 *
	 * <p>마감시간이 지났는지와는 무관하다. 마감 후는 주문·입금·수령이 진행되는 구간이고,
	 * 참여자에게는 오히려 그때 팟 정보(총대 계좌, 만날 장소)가 필요하다.
	 * 달라지는 건 전체 배달팟 목록에서 빠져 새 사람이 못 들어온다는 것뿐이다.
	 */
	ACTIVE,

	/**
	 * 나눔 완료. 배달을 받아 나누는 것까지 끝났다는 뜻이고, 참여자를 포함한 모두의 목록에서 사라진다.
	 * 채팅방은 그대로 남아 하단 채팅 탭에서 계속 볼 수 있다.
	 *
	 * <p>총대의 나눔 완료 버튼, 또는 마감시간 + 5시간 경과로 자동 전이된다.
	 */
	DONE
}
